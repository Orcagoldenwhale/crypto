/**
 * Строгие TypeScript-типы для всего домена.
 *
 * ВАЖНО: имена полей с подчёркиванием (vpoc_price, delta_at_low и т.д.)
 * сохранены намеренно — это контракт с Python-pipeline (см. docs/03-data-format.md).
 * При выгрузке из Python в JSON и при чтении на фронте поля совпадают побайтово.
 */

// ============================================================================
// Базовые единицы измерения
// ============================================================================

/** Unix-время в миллисекундах */
export type TimestampMs = number;

/** Цена в quote-валюте (для BTCUSDT — USDT) */
export type Price = number;

/** Объём (в base-валюте, например в BTC) */
export type Volume = number;

// ============================================================================
// Кластер (один ценовой уровень внутри 5m свечи)
// ============================================================================

/**
 * Агрегированный объём на одном ценовом уровне за 5 минут.
 *
 * - bid = объём агрессивных продаж (taker SELL, удар в bid-сторону стакана)
 * - ask = объём агрессивных покупок (taker BUY, удар в ask-сторону стакана)
 * - vol = bid + ask (инвариант)
 * - delta = ask - bid (инвариант)
 */
export interface Cluster {
  /** Нижняя граница ценового бакета, выровнена на tick_size */
  price: Price;
  /** Объём агрессивных продаж */
  bid: Volume;
  /** Объём агрессивных покупок */
  ask: Volume;
  /** Общий объём уровня = bid + ask */
  vol: Volume;
  /** Дельта уровня = ask - bid (>0: доминируют покупки) */
  delta: number;
}

// ============================================================================
// Свечи
// ============================================================================

/**
 * 5-минутная свеча с полной кластерной разбивкой (LTF).
 * Это основной формат данных в системе — всё остальное вычисляется отсюда.
 */
export interface Candle5m {
  /** Unix ms, начало 5-минутного окна (выровнено на 5m сетку UTC) */
  timestamp: TimestampMs;
  open: Price;
  high: Price;
  low: Price;
  close: Price;

  /** Общий объём свечи = sum(clusters[].vol) */
  volume: Volume;
  /** Общая дельта свечи = sum(clusters[].delta) */
  delta: number;

  /** Цена кластера с максимальным объёмом (Volume Point of Control) */
  vpoc_price: Price;
  /** Максимальный объём кластера в свече (для нормализации гистограммы) */
  max_vol: Volume;

  /** Дельта кластера на уровне low (0 если такого кластера нет) */
  delta_at_low: number;
  /** Дельта кластера на уровне high (0 если такого кластера нет) */
  delta_at_high: number;

  /** Кластеры по уровням, отсортированы по возрастанию price */
  clusters: Cluster[];
}

/**
 * 15-минутная свеча для HTF-разметки.
 * Строится агрегацией 3×5m. Кластеры на HTF не нужны — там только структурный анализ.
 */
export interface Candle15m {
  timestamp: TimestampMs;
  open: Price;
  high: Price;
  low: Price;
  close: Price;
  volume: Volume;
}

/**
 * Часовая свеча для HTF-разметки (POI на 1h).
 * Строится агрегацией 12×5m. Кластеры не нужны — структурный контекст.
 */
export interface Candle1h {
  timestamp: TimestampMs;
  open: Price;
  high: Price;
  low: Price;
  close: Price;
  volume: Volume;
}

// ============================================================================
// Метаданные датасета (приходят из Python-pipeline)
// ============================================================================

/** Длительность слота графика: 1h / 15m / 5m (HTF или LTF в зависимости от выбранной пары). */
export type ChartTimeframe = '1h' | '15m' | '5m';

/** Алиас для обратной совместимости в импортах. */
export type Timeframe = ChartTimeframe;

/**
 * Пара таймфреймов: старший (зоны POI) → младший (сканер, footprint, входы).
 *
 * Данные по-прежнему приходят как 5m из pipeline; 1h и 15m строятся на лету.
 *
 * Двухуровневые пары (HTF → LTF):
 *   - '1h-15m' / '1h-5m' / '15m-5m'
 *
 * Single-режим (HTF == LTF): зоны и сканер на одном экране.
 *   - '1h-1h' / '15m-15m' / '5m-5m'
 */
export type TfPairId =
  | '1h-15m'
  | '1h-5m'
  | '15m-5m'
  | '1h-1h'
  | '15m-15m'
  | '5m-5m';

export interface DatasetMeta {
  /** Тикер в верхнем регистре, например 'BTCUSDT' */
  symbol: string;
  /** Биржа, например 'binance' */
  exchange: string;
  /** На фронте всегда 5m — HTF строится на лету */
  timeframe: '5m';
  /** Шаг ценовых уровней (для BTC обычно 5) */
  tick_size: number;
  /** ISO-8601 нижняя граница периода (UTC) */
  from: string;
  /** ISO-8601 верхняя граница периода (UTC, эксклюзивно) */
  to: string;
  /** Количество свечей (для быстрой проверки целостности) */
  candles_count: number;
  /** Когда сгенерирован файл */
  generated_at: string;
  /** Откуда взяты сырые данные */
  source: string;
  /** Версия схемы */
  version: number;
}

export interface Dataset {
  meta: DatasetMeta;
  candles: Candle5m[];
}

