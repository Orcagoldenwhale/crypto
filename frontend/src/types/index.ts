// ============================================================================
// Сканер
// ============================================================================

export type SignalType = 'LONG' | 'SHORT';

/**
 * Численная диагностика 4 правил сканера для одной свечи.
 *
 * Это РЕАЛЬНЫЕ значения метрик в момент сигнала (а не выдуманные пороги),
 * чтобы UI мог честно показать «почему именно эта свеча».
 *
 * Для LONG-сигнала смотрим: polarity (close vs mid), totalDelta > 0,
 * close vs vpoc, delta_at_low (поглощение продавцов в низу свечи).
 * Для SHORT — зеркально.
 */
export interface SignalDiagnostics {
  /** OHLC исходной свечи — для отрисовки бейджей и подсветки. */
  open: Price;
  high: Price;
  low: Price;
  close: Price;

  /** Средняя цена свечи (high+low)/2 — порог правила polarity. */
  mid: Price;

  /** Суммарная дельта свечи (ask − bid). */
  totalDelta: number;

  /** Цена кластера с максимальным объёмом. */
  vpoc_price: Price;

  /** delta-кластер на уровне low (поглощение продавцов для LONG). */
  delta_at_low: number;
  /** delta-кластер на уровне high (поглощение покупателей для SHORT). */
  delta_at_high: number;

  /** Объём кластера на уровне low (для контекста бэйджа). */
  vol_at_low: Volume;
  /** Объём кластера на уровне high. */
  vol_at_high: Volume;

  // ===== Бонус-индикаторы (НЕ влияют на наличие сигнала) ==========
  // Эти поля — дополнительные подсказки для пользователя по качеству входа.
  // Сигнал считается «жирнее», если бонусов много, но он валиден и без них.

  /**
   * Количество одноцветных имбалансов в свече.
   *
   * Имбаланс = `ask ≥ 2 × bid` (бычий, зелёный) или `bid ≥ 2 × ask` (медвежий, красный).
   * Для LONG считаем бычьи (поток покупок), для SHORT — медвежьи (поток продаж).
   *
   * «Россыпь одноцветных» — классический order-flow паттерн: много таких уровней
   * подряд указывает на агрессивное направленное движение.
   */
  imbalanceCount: number;

  /** Цены ячеек, на которых сработал имбаланс — для подсветки на свече. */
  imbalancePrices: Price[];

  /**
   * Нуль на экстремуме свечи (исчерпание аукциона).
   *
   * - LONG  → на самом нижнем кластере (low) `ask == 0` (на лоу нет агрессивных покупок).
   * - SHORT → на самом верхнем кластере (high) `bid == 0` (на хае нет агрессивных продаж).
   *
   * Отсутствие потока на экстремуме интерпретируется как «никто больше не толкает
   * цену в эту сторону» — повышает вероятность разворота.
   */
  hasZeroAtExtreme: boolean;
}

export interface Signal {
  /** Уникальный ID сигнала — нужен для hover/select-логики в UI. */
  id: string;
  /** Timestamp 5m свечи, на которой найден сигнал */
  candleTime: TimestampMs;
  type: SignalType;
  /** Цена для маркера (low для LONG, high для SHORT) */
  price: Price;
  /** ID зоны, внутри которой найден сигнал */
  zoneId: string;
  /** Численные значения 4 правил — для детальной карточки и подсветки. */
  diagnostics: SignalDiagnostics;
}

export interface ScannerReport {
  zonesTotal: number;
  zonesWithSignal: number;
  signalsTotal: number;
  longCount: number;
  shortCount: number;
}

// ============================================================================
// Live-режим (real-time через Binance WebSocket)
// ============================================================================

/**
 * Один тик из стрима aggTrade.
 *
 * Поле `aggTradeId` критично для восстановления пропусков (gap recovery):
 * после reconnect мы запрашиваем REST `/api/v3/aggTrades?fromId=lastId+1`
 * и склеиваем недостающие тики обратно в свечу.
 *
 * Семантика `isBuyerMaker`:
 *   true  → агрессивный SELL по рынку (taker ударил в bid → bid +qty),
 *   false → агрессивный BUY  по рынку (taker ударил в ask → ask +qty).
 */
export interface AggTradeTick {
  /** Unix ms — время сделки на бирже (поле `T` в WS). */
  timestamp: TimestampMs;
  /** Цена сделки. */
  price: Price;
  /** Объём сделки. */
  qty: Volume;
  /** true=рыночная продажа (bid +=), false=рыночная покупка (ask +=). */
  isBuyerMaker: boolean;
  /** ID агрегированной сделки (поле `a` в WS) — для дедупликации/восстановления. */
  aggTradeId: number;
}

/**
 * Состояния машины live-режима.
 *
 * - idle           — выключен, ничего не происходит.
 * - connecting     — открываем WebSocket, ещё нет тиков.
 * - gap-filling    — догоняем пропущенные тики через REST после reconnect / reload.
 * - live           — стабильно идёт поток.
 * - reconnecting   — WS отвалился, пытаемся переподключиться.
 * - error          — фатальная ошибка (например, символ не существует).
 */
export type LiveStatus =
  | 'idle'
  | 'connecting'
  | 'gap-filling'
  | 'live'
  | 'reconnecting'
  | 'error';
